import "dotenv/config";

import { pool, query } from "../src/config/db.js";

try {
  await query(`
    create table if not exists public.project_requirements (
      id bigint generated by default as identity primary key,
      project_id bigint not null,
      description text not null,
      sort_order integer not null default 0,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      deleted_at timestamptz,
      constraint fk_project_requirements_project
        foreign key (project_id)
        references public.projects(id)
        on delete cascade,
      constraint chk_project_requirements_description
        check (length(trim(description)) > 0),
      constraint chk_project_requirements_sort_order
        check (sort_order >= 0)
    );

    create index if not exists idx_project_requirements_project
      on public.project_requirements(project_id, sort_order, id)
      where deleted_at is null;

    create table if not exists public.project_technical_specifications (
      id bigint generated by default as identity primary key,
      project_id bigint not null,
      title varchar(150) not null,
      description text,
      sort_order integer not null default 0,
      default_open boolean not null default false,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      deleted_at timestamptz,
      constraint fk_project_technical_specifications_project
        foreign key (project_id)
        references public.projects(id)
        on delete cascade,
      constraint chk_project_technical_specifications_title
        check (length(trim(title)) > 0),
      constraint chk_project_technical_specifications_sort_order
        check (sort_order >= 0)
    );

    create index if not exists idx_project_technical_specifications_project
      on public.project_technical_specifications(project_id, sort_order, id)
      where deleted_at is null;

    create table if not exists public.project_technical_specification_items (
      id bigint generated by default as identity primary key,
      specification_id bigint not null,
      content text not null,
      sort_order integer not null default 0,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      deleted_at timestamptz,
      constraint fk_project_technical_specification_items_specification
        foreign key (specification_id)
        references public.project_technical_specifications(id)
        on delete cascade,
      constraint chk_project_technical_specification_items_content
        check (length(trim(content)) > 0),
      constraint chk_project_technical_specification_items_sort_order
        check (sort_order >= 0)
    );

    create index if not exists idx_project_technical_specification_items_spec
      on public.project_technical_specification_items(
        specification_id,
        sort_order,
        id
      )
      where deleted_at is null;
  `);

  const projectResult = await query(
    `
      select id
      from public.projects
      where lower(name) = lower($1)
        and deleted_at is null
      limit 1
    `,
    ["Quinta Bella Vista"],
  );
  const projectId = projectResult.rows[0]?.id;

  if (projectId) {
    await query(
      `
        update public.project_requirements
        set description = case description
          when 'Area social integrada' then 'Área social integrada'
          when 'Iluminacion calida' then 'Iluminación cálida'
          else description
        end,
        updated_at = now()
        where project_id = $1
          and description in ('Area social integrada', 'Iluminacion calida')
          and deleted_at is null
      `,
      [projectId],
    );

    await query(
      `
        update public.project_technical_specifications
        set
          title = case
            when title = 'Zonificacion' then 'Zonificación'
            else title
          end,
          description = case
            when description =
              'Equipos y herramientas empleados durante el levantamiento y la ejecucion del proyecto.'
              then
              'Equipos y herramientas empleados durante el levantamiento y la ejecución del proyecto.'
            else description
          end,
          updated_at = now()
        where project_id = $1
          and deleted_at is null
      `,
      [projectId],
    );

    await query(
      `
        update public.project_technical_specification_items item
        set
          content = case item.content
            when 'Habitacion principal: 18 mts'
              then 'Habitación principal: 18 mts'
            when 'Revision de requerimientos del cliente.'
              then 'Revisión de requerimientos del cliente.'
            when 'Validacion de materiales y cronograma.'
              then 'Validación de materiales y cronograma.'
            when 'Coordinacion de aprobaciones previas a ejecucion.'
              then 'Coordinación de aprobaciones previas a ejecución.'
            when 'Condiciones de iluminacion natural y asoleamiento.'
              then 'Condiciones de iluminación natural y asoleamiento.'
            when 'Condiciones de ventilacion y circulacion interior.'
              then 'Condiciones de ventilación y circulación interior.'
            when 'Lavanderia' then 'Lavandería'
            else item.content
          end,
          updated_at = now()
        from public.project_technical_specifications specification
        where item.specification_id = specification.id
          and specification.project_id = $1
          and item.deleted_at is null
          and specification.deleted_at is null
      `,
      [projectId],
    );

    const requirements = [
      "Cocina abierta",
      "Área social integrada",
      "Iluminación cálida",
      "Espacios funcionales",
    ];

    for (const [index, description] of requirements.entries()) {
      await query(
        `
          insert into public.project_requirements (
            project_id,
            description,
            sort_order
          )
          select $1, $2, $3
          where not exists (
            select 1
            from public.project_requirements
            where project_id = $1
              and lower(description) = lower($2)
              and deleted_at is null
          )
        `,
        [projectId, description, index],
      );
    }

    const specifications = [
      {
        title: "Zonificación",
        defaultOpen: true,
        items: [
          "Habitación principal: 18 mts",
          "Habitaciones secundarias: 15 mts c/u",
          "Cocina: 10 mts",
          "Sala",
          "Comedor",
          "Lavandería",
        ],
      },
      {
        title: "Procedimientos",
        items: [
          "Revisión de requerimientos del cliente.",
          "Validación de materiales y cronograma.",
          "Coordinación de aprobaciones previas a ejecución.",
        ],
      },
      {
        title: "Condiciones",
        items: [
          "Condiciones de iluminación natural y asoleamiento.",
          "Condiciones de ventilación y circulación interior.",
          "Condiciones del entorno inmediato y accesos.",
        ],
      },
      {
        title: "Equipo utilizado",
        description:
          "Equipos y herramientas empleados durante el levantamiento y la ejecución del proyecto.",
        items: [],
      },
    ];

    for (const [specificationIndex, specification] of specifications.entries()) {
      const specificationResult = await query(
        `
          insert into public.project_technical_specifications (
            project_id,
            title,
            description,
            sort_order,
            default_open
          )
          select
            $1::bigint,
            $2::varchar,
            $3::text,
            $4::integer,
            $5::boolean
          where not exists (
            select 1
            from public.project_technical_specifications
            where project_id = $1
              and lower(title) = lower($2::varchar)
              and deleted_at is null
          )
          returning id
        `,
        [
          projectId,
          specification.title,
          specification.description || null,
          specificationIndex,
          Boolean(specification.defaultOpen),
        ],
      );

      let specificationId = specificationResult.rows[0]?.id;

      if (!specificationId) {
        const existingSpecification = await query(
          `
            select id
            from public.project_technical_specifications
            where project_id = $1
              and lower(title) = lower($2)
              and deleted_at is null
            order by id
            limit 1
          `,
          [projectId, specification.title],
        );
        specificationId = existingSpecification.rows[0]?.id;
      }

      for (const [itemIndex, content] of specification.items.entries()) {
        await query(
          `
            insert into public.project_technical_specification_items (
              specification_id,
              content,
              sort_order
            )
            select $1, $2, $3
            where not exists (
              select 1
              from public.project_technical_specification_items
              where specification_id = $1
                and lower(content) = lower($2)
                and deleted_at is null
            )
          `,
          [specificationId, content, itemIndex],
        );
      }
    }
  }

  const verification = await query(`
    select table_name
    from information_schema.tables
    where table_schema = 'public'
      and table_name in (
        'project_requirements',
        'project_technical_specifications',
        'project_technical_specification_items'
      )
    order by table_name
  `);

  console.log(JSON.stringify(verification.rows, null, 2));
} finally {
  await pool.end();
}
